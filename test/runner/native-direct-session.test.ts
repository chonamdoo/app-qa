import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { copyFileSync, cpSync, existsSync, readFileSync, rmSync, symlinkSync } from 'node:fs';
import { join } from 'node:path';
import { it } from 'node:test';
import { createExecutionAdmission } from '../../src/core/admission.ts';
import { createAgentClient } from '../../src/core/agent-client.ts';
import { ensureDir, sha256, writeJsonAtomic } from '../../src/core/fsx.ts';
import { createAgentService } from '../../src/runner/index.ts';
import { fixture } from '../fixtures/project-fixture.ts';

it('opens an owned Chrome direct session under its exact admission scope and disposes executed source before releasing it', { skip: process.env.QA_OWNED_CHROME_FIXTURE !== '1', timeout: 60_000 }, async t => {
  const f = await fixture(t, { retain: true });
  for (const name of ['src', 'bin']) cpSync(join(process.cwd(), name), join(f.root, name), { recursive: true });
  for (const name of ['package.json', 'package-lock.json']) copyFileSync(join(process.cwd(), name), join(f.root, name));
  symlinkSync(join(process.cwd(), 'node_modules'), join(f.root, 'node_modules'));
  const tools = ensureDir(join(f.root, '.tools', 'chromedriver'));
  copyFileSync(join(process.cwd(), '.tools', 'chromedriver', 'chromedriver-mac-arm64_v156.0.8078.80'), join(tools, 'chromedriver-mac-arm64_v156.0.8078.80'));
  const admission = createExecutionAdmission(join(f.root, '.qa', 'direct-admission'));
  const profileId = randomUUID();
  const service = createAgentService({ root: f.root, appsDir: join(f.root, 'apps'), runsDir: join(f.root, '.qa', 'runs'), inventoryDir: join(f.root, '.qa', 'inventory'), fixturesDir: join(f.root, 'fixtures'), ocr: null, admission,
    instanceProfiles: async () => [{ id: profileId, name: 'Owned direct fixture', platform: 'desktop-chrome', runtime: 'owned-chrome' }] });
  let completed = false;
  t.after(async () => { await service.shutdown(); if (completed) rmSync(f.root, { recursive: true }); });
  const reviewer = { principalId: 'local-native-fixture-reviewer', channel: 'local-ui' as const };
  const created = await service.call({ method: 'instance.create', requestId: randomUUID(), profileId }, { operatorReview: reviewer });
  assert.ok(created.ok);
  const instance = created.result;
  assert.ok(instance && typeof instance === 'object' && 'id' in instance && typeof instance.id === 'string');
  const deviceId = `chrome:${instance.id}`;
  writeJsonAtomic(join(f.root, 'apps', 'shop.yaml'), { id: 'shop', name: 'Explicit synthetic direct fixture', web: { url: f.origin, origins: [f.origin], platforms: ['desktop-chrome'], viewport: { width: 1280, height: 800 } }, agent: { data: 'synthetic-fixture', screenshots: true, deviceIds: [deviceId], mutations: ['type'], coordinates: false } });
  const prepared = await service.call({ method: 'instance.prepare', instanceId: instance.id }, { operatorReview: reviewer });
  assert.ok(prepared.ok);
  const client = createAgentClient((request, signal) => service.call(request, { signal }));
  await assert.rejects(client.request({ method: 'session.open', app: 'shop', platform: 'desktop-chrome', deviceId: `chrome:${randomUUID()}` }), { code: 'scope_denied' });
  const opened = await client.request({ method: 'session.open', app: 'shop', platform: 'desktop-chrome', deviceId });
  assert.equal(opened.state, 'ready');
  assert.equal(opened.capabilities.hostGlobalInput, false);
  assert.equal(opened.capabilities.isolation, 'owned-browser-context');
  const literal = '${HOME}/owned-native-private-input';
  const source = `export default async function (qa) { const session = qa.session(qa.sessionIds[0]); const observation = await session.observe(); const input = observation.candidates.find(candidate => candidate.resourceId === 'note'); if (!input) throw new Error('Missing fixture input'); await session.type(input.ref, ${JSON.stringify(literal)}, { expectNoChange: true }); await session.assertText(${JSON.stringify(literal)}); return { verified: true }; }`;
  const script = await client.runScript({ source, sessionIds: [opened.sessionId], deadlineMs: 15_000 });
  assert.equal(script.state, 'completed', JSON.stringify(script));
  assert.equal(JSON.stringify(script).includes(literal), false);
  const directory = join(f.root, '.qa', 'agent-scripts', script.scriptId);
  const stored = JSON.parse(readFileSync(join(directory, 'status.json'), 'utf8'));
  assert.equal(stored.sourceSha256, sha256(source));
  assert.equal(stored.sourceFile, 'script.mjs');
  assert.equal(typeof stored.sourceDisposedAt, 'string');
  assert.equal(existsSync(join(directory, stored.sourceFile)), false);
  assert.equal(JSON.stringify(stored).includes(literal), false);
  const closed = await client.session(opened.sessionId).close();
  assert.equal(closed.state, 'closed');
  const summary = JSON.parse(readFileSync(join(f.root, '.qa', 'runs', opened.runId, 'summary.json'), 'utf8'));
  assert.equal(summary.tests[0].verdict, 'PASS');
  assert.equal(f.state.appliedEffects, 0);
  assert.equal(admission.status().state, 'idle');
  completed = true;
});
